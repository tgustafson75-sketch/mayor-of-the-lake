// Bundles the public talk API into one self-contained file for Vercel.
// Vercel's ESM runtime cannot resolve the project's extensionless imports, so the
// function ships as a single bundle with every dependency inside. Run before deploy.
import { build } from "esbuild";

await build({
  entryPoints: ["server/vercel-entry.ts"],
  outfile: "api/[...route].js",
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  banner: { js: "// Generated by scripts/build-api.mjs. Do not edit: edit server/vercel-entry.ts." },
});
console.log("built api/[...route].js");
